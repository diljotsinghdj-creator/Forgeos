#!/usr/bin/env python3
"""Check case studies for structure and honesty, and rebuild case_studies/INDEX.md.

Usage:
  python3 case_study_check.py <skill_dir>/case_studies           # check all, rewrite INDEX.md
  python3 case_study_check.py <skill_dir>/case_studies/x.md      # check one

A case study must:
  - have the frontmatter fields of assets/templates/case_study.md, with a real URL and an evidence_basis;
  - have the twelve numbered sections plus Sources, each non-empty;
  - tag claims with [V], [I] or [O] (at least one [V] backed by a URL in Sources);
  - only give timestamps (m:ss) if the evidence basis names a transcript or chapter list.
Exit 0 = all pass, 1 = problems found.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

FIELDS = ("id", "title", "url", "category", "evidence_basis")
SECTIONS = ("Subject and central question", "Opening technique", "Narrative structure", "Narration characteristics",
            "Visual techniques", "Graphics and animation", "Footage selection", "Editing techniques", "Sound design",
            "Transitions", "What makes it effective", "What we can adapt")
TS = re.compile(r"(?<![\d:])\d{1,2}:\d{2}(?![\d:])")


def parse(path: Path):
    text = path.read_text(encoding="utf-8")
    fm = {}
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if m:
        key = None
        for line in m.group(1).splitlines():
            if ":" in line and not line.startswith((" ", "\t", "-")):
                k, v = line.split(":", 1)
                key = k.strip()
                v = v.strip()
                fm[key] = "" if v in (">", "|", ">-", "|-") else v.strip('"')
            elif key and line.strip():  # continuation of a folded / literal / list value
                fm[key] = (fm[key] + " " + line.strip()).strip()
        body = text[m.end():]
    else:
        body = text
    return fm, body


def check(path: Path) -> list[str]:
    fm, body = parse(path)
    out = []
    for f in FIELDS:
        if not fm.get(f) or fm[f].startswith("<"):
            out.append(f"frontmatter '{f}' missing or placeholder")
    gaps = []
    if fm.get("url") and not fm["url"].startswith("http"):
        if "not confirmed" in fm["url"].lower():
            gaps.append("url not confirmed")
        else:
            out.append("url is not a link and not marked 'not confirmed'")
    heads = re.split(r"^## ", body, flags=re.M)
    found = {}
    for h in heads[1:]:
        title, _, content = h.partition("\n")
        t = re.sub(r"^\d+\.\s*", "", title).strip()
        found[t.split("(")[0].strip()] = content.strip()
    for s in SECTIONS:
        hit = next((v for k, v in found.items() if k.lower().startswith(s.lower())), None)
        if hit is None:
            out.append(f"section missing: {s}")
        elif len(hit) < 40:
            if "not verified" in hit.lower() or "not accessed" in hit.lower():
                gaps.append(f"unverified: {s}")
            else:
                out.append(f"section too thin: {s}")
    src = next((v for k, v in found.items() if k.lower().startswith("sources")), "")
    if "http" not in src:
        out.append("Sources lists no URLs")
    if "[V]" not in body:
        out.append("no [V] verified statement")
    eb = fm.get("evidence_basis", "").lower()
    has_ts_source = any(w in eb for w in ("transcript", "chapter", "caption", "timestamp"))
    analysis = body.split("## Sources")[0]
    if TS.search(analysis) and not has_ts_source:
        out.append("timestamps given but evidence_basis names no transcript or chapter list")
    return out, gaps


def index(folder: Path):
    rows = []
    for p in sorted(folder.glob("*.md")):
        if p.name in ("INDEX.md", "README.md", "PATTERNS.md", "CHANNEL_SAMPLE.md", "TRANSCRIPT_STUDY.md"):
            continue
        fm, _ = parse(p)
        basis = fm.get("evidence_basis", "")
        rows.append(f"| [{fm.get('title', p.stem)}]({p.name}) | {fm.get('category', '')} | {fm.get('series', '')} | "
                    f"{fm.get('length', '')} | {basis[:90] + ('…' if len(basis) > 90 else '')} |")
    head = ("# Case study index\n\nGenerated by `scripts/case_study_check.py`; do not edit by hand.\n"
            "Evidence labels inside each file: [V] verified by a cited source, [I] informed interpretation, "
            "[O] our original adaptation.\n\n| Video | Category | Series | Length | Evidence basis |\n|---|---|---|---|---|\n")
    (folder / "INDEX.md").write_text(head + "\n".join(rows) + f"\n\n{len(rows)} case studies.\n", encoding="utf-8")
    return len(rows)


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    p = Path(argv[0])
    files = [p] if p.is_file() else sorted(x for x in p.glob("*.md") if x.name not in ("INDEX.md", "README.md", "PATTERNS.md", "CHANNEL_SAMPLE.md", "TRANSCRIPT_STUDY.md"))
    bad = 0
    total_gaps = []
    for f in files:
        probs, gaps = check(f)
        total_gaps.extend(gaps)
        if probs:
            bad += 1
            print(f"FAIL {f.name}")
            for q in probs:
                print(f"     - {q}")
        else:
            print(f"ok   {f.name}" + (f"  ({len(gaps)} declared gaps)" if gaps else ""))
    if total_gaps:
        from collections import Counter
        c = Counter(g.split(": ")[-1] if g.startswith("unverified") else g for g in total_gaps)
        print("declared gaps (honest, to close in the next research pass): " + ", ".join(f"{k} x{v}" for k, v in c.most_common()))
    if p.is_dir():
        n = index(p)
        print(f"INDEX.md rebuilt: {n} case studies")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
