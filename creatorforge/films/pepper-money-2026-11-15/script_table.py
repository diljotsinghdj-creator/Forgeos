def dur(vo, cam):
    return len(re.findall(r"[\w'’₹,.-]+", vo)) / WPS + .6 * cam.count("[HOLD") + .2 * cam.count("[CUT]")


def build():
    out, t, holds, flags = [], 0.0, [], []
    for act, rows in ACTS:
        out.append(f"\n## {act}\n\n| Beat / Time | Voiceover (spoken) | Canvas layer (what's on screen) | Camera & motion cue |\n|---|---|---|---|")
        for beat, vo, canvas, cam, frame, kind in rows:
            d = dur(vo, cam)
            shots = int(kind[1:] or 1)
            lim = 4.5 if kind[0] == "s" else 7.0
            if d / shots > lim:
                flags.append(f"{beat} @ {t:.1f}s: {d / shots:.1f}s per {'still' if kind[0] == 's' else 'building'} shot ({vo[:40]}…)")
            holds += [d / shots] * shots
            out.append(f"| {beat} · {int(t // 60)}:{int(t % 60):02d} | {vo} | {canvas} <br>`frame: {frame}` | {cam} |")
            t += d
    return "\n".join(out), t, holds, flags


if __name__ == "__main__":
    body, total, holds, flags = build()
    avg = sum(holds) / len(holds)
    head = (D / "script_table_head.md").read_text(encoding="utf-8")
    tail = (D / "script_table_tail.md").read_text(encoding="utf-8")
    stats = (f"\n**Timing (computed):** {len(holds)} shots · narration about {int(total // 60)}:{int(total % 60):02d} at ~150 WPM "
             f"(music beds, holds and act breaks bring the cut to about 8½–9 min) · average hold {avg:.1f} s · longest {max(holds):.1f} s · "
             f"pacing flags: {len(flags) or 'none'}.\n")
    (D / "SCRIPT_TABLE.md").write_text(head + stats + body + "\n" + tail, encoding="utf-8")
    print(f"rows {len(holds)} total {total:.0f}s avg {avg:.2f} max {max(holds):.2f}")
    print("\n".join(flags) or "no pacing flags")
